# -*- coding: utf-8 -*-
"""sha256 integrity of the shipped evidence pack (``crh verify``).

``data/evidence.sha256`` is a plain-text manifest, GNU coreutils layout::

    <sha256 hex>  <path relative to the repository root>

The manifest covers every file under ``data/`` and does not list itself. That
makes the check two-sided: a modified file is ``MODIFIED``, a deleted one is
``MISSING``, and a silently added one is ``UNLISTED``. All three fail the run.

``crh verify --write`` regenerates the manifest from the files on disk. It is the
only command in the CLI that touches ``data/`` and it only rewrites that one
file — the evidence files themselves are never modified by this package.
"""
from __future__ import annotations

from pathlib import Path
from typing import Dict, List, Optional

from .paths import MANIFEST_REL, iter_files, sha256_file

MANIFEST_HEADER = """\
# sha256 manifest for the shipped evidence pack (data/).
# Generated by `crh verify --write` (Crisis Rehearsal Engine v0.3.0).
# Format: <sha256>  <path relative to the repository root>, one file per line.
# The manifest does not list itself; a file under data/ that is absent here is
# reported as UNLISTED and fails `crh verify`, so any edit to the evidence pack
# must be committed together with a regenerated manifest.
"""


def data_root(repo: Path) -> Path:
    return Path(repo) / "data"


def manifest_path(repo: Path) -> Path:
    return Path(repo) / MANIFEST_REL


def data_files(repo: Path) -> List[Path]:
    """Every file under data/, except the manifest itself, sorted by path."""
    repo = Path(repo)
    base = data_root(repo)
    manifest = manifest_path(repo).resolve()
    files = []
    for path in iter_files(base):
        try:
            if path.resolve() == manifest:
                continue
        except OSError:
            pass
        files.append(path)
    return files


def _rel(repo: Path, path: Path) -> str:
    return path.resolve().relative_to(Path(repo).resolve()).as_posix()


def build_manifest_text(repo: Path) -> str:
    """Deterministic manifest text for the current contents of data/."""
    repo = Path(repo)
    lines = [MANIFEST_HEADER]
    for path in data_files(repo):
        lines.append(f"{sha256_file(path)}  {_rel(repo, path)}")
    return "\n".join(lines) + "\n"


def write_manifest(repo: Path) -> Path:
    """Rewrite data/evidence.sha256 and return its path."""
    target = manifest_path(repo)
    target.parent.mkdir(parents=True, exist_ok=True)
    with open(str(target), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(build_manifest_text(repo))
    return target


def read_manifest(repo: Path) -> Optional[Dict[str, str]]:
    """Parse the manifest into {repo-relative path: sha256}; None when absent."""
    path = manifest_path(repo)
    if not path.is_file():
        return None
    entries: Dict[str, str] = {}
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return None
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split(None, 1)
        if len(parts) != 2:
            continue
        digest, relpath = parts[0].lower(), parts[1].strip().lstrip("*")
        if len(digest) == 64:
            entries[relpath.replace("\\", "/")] = digest
    return entries


OK = "OK"
MODIFIED = "MODIFIED"
MISSING = "MISSING"
UNLISTED = "UNLISTED"


def verify(repo: Path) -> dict:
    """Compare data/ against the manifest.

    Returns a dict with ``ok``, ``manifest_present``, per-file ``rows`` and
    ``counts``. Rows are ordered: manifest entries first (OK/MODIFIED/MISSING),
    then unlisted files.
    """
    repo = Path(repo)
    entries = read_manifest(repo)
    rows: List[dict] = []
    if entries is None:
        return {
            "ok": False,
            "manifest_present": False,
            "manifest": MANIFEST_REL.as_posix(),
            "rows": [],
            "counts": {OK: 0, MODIFIED: 0, MISSING: 0, UNLISTED: 0},
            "n_files": 0,
            "message": "manifest missing: run `crh verify --write` to generate it",
        }

    on_disk = {}
    for path in data_files(repo):
        relpath = _rel(repo, path)
        on_disk[relpath] = path

    for relpath in sorted(entries):
        expected = entries[relpath]
        path = repo / relpath
        if not path.is_file():
            rows.append({"path": relpath, "status": MISSING,
                         "expected": expected, "actual": None})
            continue
        actual = sha256_file(path)
        rows.append({
            "path": relpath,
            "status": OK if actual == expected else MODIFIED,
            "expected": expected,
            "actual": actual,
        })

    for relpath in sorted(set(on_disk) - set(entries)):
        rows.append({"path": relpath, "status": UNLISTED,
                     "expected": None, "actual": sha256_file(on_disk[relpath])})

    counts = {OK: 0, MODIFIED: 0, MISSING: 0, UNLISTED: 0}
    for row in rows:
        counts[row["status"]] += 1
    ok = (counts[MODIFIED] == 0 and counts[MISSING] == 0 and counts[UNLISTED] == 0)
    return {
        "ok": ok,
        "manifest_present": True,
        "manifest": MANIFEST_REL.as_posix(),
        "rows": rows,
        "counts": counts,
        "n_files": len(entries),
        "message": "",
    }


def as_text(result: dict, repo: Path, verbose: bool = True) -> str:
    """Human-readable ``crh verify`` output."""
    lines: List[str] = []
    add = lines.append
    add("Crisis Rehearsal Engine — evidence integrity (crh verify)")
    add("=" * 78)
    add(f"repo     : {repo}")
    add(f"manifest : {result['manifest']}")
    if not result["manifest_present"]:
        add("")
        add(f"FAILED — {result['message']}")
        return "\n".join(lines)

    add(f"files    : {result['n_files']} listed")
    add("")
    if verbose:
        for row in result["rows"]:
            if row["status"] == OK:
                add(f"  [OK      ] {row['path']}  sha256 {row['actual'][:16]}")
            elif row["status"] == MODIFIED:
                add(f"  [MODIFIED] {row['path']}")
                add(f"             expected {row['expected']}")
                add(f"             actual   {row['actual']}")
            elif row["status"] == MISSING:
                add(f"  [MISSING ] {row['path']}  (listed in the manifest, not on disk)")
            else:
                add(f"  [UNLISTED] {row['path']}  (on disk, not in the manifest)")
        add("")
    counts = result["counts"]
    add(f"summary  : {counts[OK]} OK, {counts[MODIFIED]} modified, "
        f"{counts[MISSING]} missing, {counts[UNLISTED]} unlisted")
    if result["ok"]:
        add("result   : PASS — the evidence pack matches data/evidence.sha256")
    else:
        add("result   : FAIL — the evidence pack drifted from data/evidence.sha256.")
        add("           If the change is intentional, regenerate the manifest with")
        add("           `crh verify --write` and review the diff before committing.")
    return "\n".join(lines)
